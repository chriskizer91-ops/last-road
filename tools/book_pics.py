"""The field book's pictures of the Old Hands' glyphs: each glyph tile's front view (his C02 set, models/assets/C02/
<name>_view_front.png), cut to the tile and made small, all in one sheet (8 across), for the book's pages.
Written into src/lr-book.js (window.LR_BOOK: the sheet, the size of a cell, and the names in order).
usage: python3 tools/book_pics.py  (from last-road's top)"""
import os, io, json, base64, glob
import numpy as np
from PIL import Image
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); D = f'{ROOT}/models/assets/C02/'
names = sorted(os.path.basename(p)[:-len('_view_front.png')] for p in glob.glob(D + '*_view_front.png'))
N, COLS = 72, 8; rows = (len(names) + COLS - 1) // COLS; sheet = Image.new('RGB', (N * COLS, N * rows), (226, 214, 188))
for k, n in enumerate(names):
    im = Image.open(D + n + '_view_front.png').convert('RGB'); a = np.asarray(im).astype(int); bg = a[2, 2]
    m = np.abs(a - bg).sum(2) > 30; ys, xs = np.where(m); box = (xs.min(), ys.min(), xs.max() + 1, ys.max() + 1)
    t = im.crop(box); w, h = t.size; s = (N - 6) / max(w, h); t = t.resize((max(1, round(w * s)), max(1, round(h * s))), Image.LANCZOS)
    sheet.paste(t, ((k % COLS) * N + (N - t.width) // 2, (k // COLS) * N + (N - t.height) // 2))
b = io.BytesIO(); sheet.save(b, 'WEBP', quality=72, method=6)
open(f'{ROOT}/src/lr-book.js', 'w').write('/* GENERATED by tools/book_pics.py: the field book\'s glyph pictures */\nwindow.LR_BOOK=' + json.dumps({'sheet': 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), 'n': N, 'cols': COLS, 'names': names}, separators=(',', ':')) + ';\n')
sheet.save('/tmp/lr-book-sheet.png'); print(len(names), 'glyphs', len(b.getvalue()) // 1024, 'KB')
