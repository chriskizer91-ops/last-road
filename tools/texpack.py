"""The ground's pictures for the game: his textures (models/textures/, made by tools/textures.py) packed as the engine's
TEXPACK (one picture a ground surface, the engine's names; see the engine's 49_textures), into src/lr-texpack.js.
The concrete keeps the picture Salt & Sand already has (it isn't listed here, so lr_patch.py keeps its line).
Each: the surface, his picture, metres one picture covers on the ground.  usage: python3 tools/texpack.py"""
import base64, io, json
import numpy as np
from PIL import Image
TINT = {'GRASS': (1.04, 1.17, 1.08)}  # (sRGB multipliers: the savanna's grass a little more straw and less red, so from the air it isn't the dunes' colour)
PACK = [  # (engine surface, his picture, metres a tile, what it is)
    ('DIRT', 'H04', 3.0, 'packed red dirt (the strips, bare ground)'),
    ('DIRT2', 'H10', 3.0, 'soft creek-bed sand, in patches through the dirt'),
    ('GRASS', 'H01', 2.5, 'savanna dry grass'),
    ('ROCK', 'H15', 6.0, 'sandstone (cliffs, canyon walls, slopes)'),
    ('MUD', 'H18', 2.0, 'reed mud'),
    ('SALT', 'H12', 4.0, 'salt crust (the pans)'),
    ('GRAVEL', 'H16', 2.0, 'river gravel'),
    ('PLAYA', 'H09', 4.0, 'cracked mud'),
    ('PLANKS', 'H06', 1.5, 'weathered timber boards'),
    ('SAND', 'H13', 4.0, 'the Dune Sea\'s rippled orange sand'),
]
ID = {'DIRT': 'dirt_red', 'DIRT2': 'dirt_red_2', 'GRASS': 'grass_dry', 'ROCK': 'rock', 'MUD': 'mud_wet', 'SALT': 'salt_crust', 'GRAVEL': 'gravel',
      'PLAYA': 'playa', 'PLANKS': 'wood_planks', 'SAND': 'sand'}
out = {}
for t, pic, sc, what in PACK:
    im = Image.open(f'models/textures/{pic}.webp').convert('RGB')
    if t in TINT: im = Image.fromarray((np.asarray(im, np.float64) * np.array(TINT[t])).clip(0, 255).astype(np.uint8))
    a = np.asarray(im, np.float64) / 255; m = (np.where(a <= .04045, a / 12.92, ((a + .055) / 1.055) ** 2.4)).reshape(-1, 3).mean(0)
    b = io.BytesIO(); im.save(b, 'WEBP', quality=80, method=6)
    out[t] = {'id': ID[t], 't': t, 'm': [round(float(v), 4) for v in m], 'scale': sc, 'has': True,
              'src': 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode(), 'pic': pic, 'what': what}
    print(t, pic, [round(float(v), 3) for v in m], len(b.getvalue()) // 1024, 'KB')
open('src/lr-texpack.js', 'w').write('/* GENERATED by tools/texpack.py from his textures: the ground surfaces Ground Truth paints with his pictures */\n'
    'window.LR_TEXPACK=' + json.dumps(out) + ';\n')
